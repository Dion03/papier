// Generates src/styles/tokens.css (used in dev and the library build) and,
// when dist/ exists, dist/tokens.css + dist/tokens.json.
import { mkdirSync, writeFileSync, existsSync, copyFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import * as t from '../src/tokens/tokens.mjs';

const root = fileURLToPath(new URL('..', import.meta.url));
const vars = (obj, prefix) => Object.entries(obj).map(([k, v]) => `  --papier-${prefix}${k}: ${v};`).join('\n');
const shadows = (rgb) => [
  `  --papier-shadow-sm: 0 1px 2px rgb(${rgb} / 0.08), 0 6px 16px rgb(${rgb} / 0.08);`,
  `  --papier-shadow-md: 0 12px 30px rgb(${rgb} / 0.11);`,
  `  --papier-shadow-object: 0 24px 70px rgb(${rgb} / 0.13), 0 2px 0 rgb(255 255 255 / 0.5) inset, 0 -2px 0 rgb(${rgb} / 0.08) inset;`,
].join('\n');
const theme = (name) => {
  const { shadow, ...c } = t.themes[name];
  return `${vars(c, 'color-')}\n${shadows(shadow)}\n  color-scheme: ${name};`;
};
const typeVars = Object.entries(t.type).map(([k, [s, lh, w, tr]]) =>
  `  --papier-type-${k}-size: ${s};\n  --papier-type-${k}-line: ${lh};\n  --papier-type-${k}-weight: ${w};\n  --papier-type-${k}-tracking: ${tr};`).join('\n');

// Inside @layer papier, so unlayered app CSS (and --papier-* overrides) always wins.
const body = `:root, [data-papier-theme="light"] {
${theme('light')}
}
[data-papier-theme="dark"] {
${theme('dark')}
}
@media (prefers-color-scheme: dark) {
  [data-papier-theme="system"] {
${theme('dark').replace(/^/gm, '  ')}
  }
}
:root {
  --papier-font-display: ${t.font.display};
  --papier-font-body: ${t.font.body};
${typeVars}
${vars(t.space, 'space-')}
${vars(t.radius, 'radius-')}
${vars(t.motion, '')}
${vars(t.size, '')}
}
@media (prefers-reduced-motion: reduce) {
  :root { --papier-dur-press: 0ms; --papier-dur-color: 0ms; --papier-dur-open: 0ms; --papier-dur-close: 0ms; }
}
[data-papier-motion="reduced"] { --papier-dur-press: 0ms; --papier-dur-color: 0ms; --papier-dur-open: 0ms; --papier-dur-close: 0ms; }`;
const css = `/* Generated by scripts/build-tokens.mjs from src/tokens/tokens.mjs. Do not edit. */
@layer papier {
${body}
}
`;
writeFileSync(`${root}src/styles/tokens.css`, css);
if (existsSync(`${root}dist`)) {
  copyFileSync(`${root}src/styles/tokens.css`, `${root}dist/tokens.css`);
  copyFileSync(`${root}src/styles/fonts.css`, `${root}dist/fonts.css`);
  writeFileSync(`${root}dist/tokens.json`, JSON.stringify({ primitives: t.primitives, themes: t.themes, font: t.font, type: t.type, space: t.space, radius: t.radius, motion: t.motion, size: t.size }, null, 2));
}
console.log('tokens written');
