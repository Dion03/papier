// Generates a Jetpack Compose token file from the same source as tokens.css, so
// HomeForge and Auralis can share Papier's colours, spacing, shape and motion.
import { mkdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import * as t from '../src/tokens/tokens.mjs';

const root = fileURLToPath(new URL('..', import.meta.url));
const camel = (k) => k.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
const color = (hex) => `Color(0xFF${hex.slice(1).toUpperCase()})`;
const roles = (theme) => Object.entries(t.themes[theme]).filter(([, v]) => v.startsWith('#')).map(([k, v]) => `        val ${camel(k)} = ${color(v)}`).join('\n');
const px = (v) => `${parseFloat(v)}.dp`.replace('.0.dp', '.dp');
const ms = (v) => parseInt(v, 10);
const bez = t.motion['ease-arrive'].match(/[\d.]+/g).map((n) => `${Number(n)}f`).join(', ');
const sp = (role) => t.type[role][0].startsWith('clamp') ? t.type[role][0].match(/(\d+)px\)$/)[1] : parseInt(t.type[role][0], 10);

const kt = `// Generated by papier/scripts/build-android.mjs from src/tokens/tokens.mjs. Do not edit.
package nl.dionbm.papier

import androidx.compose.animation.core.CubicBezierEasing
import androidx.compose.ui.graphics.Color
import androidx.compose.ui.unit.dp
import androidx.compose.ui.unit.sp

object PapierTokens {
    object Light {
${roles('light')}
    }

    object Dark {
${roles('dark')}
    }

    object Space {
${Object.entries(t.space).filter(([k]) => k !== '0').map(([k, v]) => `        val s${k} = ${px(v)}`).join('\n')}
    }

    object Radius {
${Object.entries(t.radius).filter(([k]) => k !== 'pill').map(([k, v]) => `        val ${k} = ${px(v)}`).join('\n')}
    }

    object Motion {
        val easeArrive = CubicBezierEasing(${bez})
${['dur-press', 'dur-color', 'dur-close', 'dur-open'].map((k) => `        const val ${camel(k.replace('dur-', ''))}Ms = ${ms(t.motion[k])}`).join('\n')}
    }

    /** Largest size per type role; Compose has no clamp(), scale down yourself on small screens. */
    object Type {
${Object.keys(t.type).map((k) => `        val ${camel(k)} = ${sp(k)}.sp`).join('\n')}
        const val displayFont = "Manrope"
        const val bodyFont = "DM Sans"
    }

    val hitTarget = ${px(t.size['hit-target'])}
}
`;
mkdirSync(`${root}dist/android`, { recursive: true });
writeFileSync(`${root}dist/android/PapierTokens.kt`, kt);
console.log('android tokens written');
